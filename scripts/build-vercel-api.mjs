import { mkdir } from "node:fs/promises";
import { build } from "esbuild";

await mkdir("api/trpc", { recursive: true });
await mkdir("api/cron", { recursive: true });

await Promise.all([
  build({
    entryPoints: ["server/vercelTrpcHandler.ts"],
    bundle: true,
    platform: "node",
    packages: "external",
    format: "esm",
    outfile: "api/trpc/[trpc].js",
    banner: {
      js: "// Generated by scripts/build-vercel-api.mjs. Do not edit by hand.",
    },
  }),
  build({
    entryPoints: ["server/calendarTaskCron.ts"],
    bundle: true,
    platform: "node",
    packages: "external",
    format: "esm",
    outfile: "api/cron/calendar-task-sync.js",
    banner: {
      js: "// Generated by scripts/build-vercel-api.mjs. Do not edit by hand.",
    },
  }),
]);
